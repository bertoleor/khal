import { existsSync, readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { describe, expect, it } from 'vitest';

/**
 * A10 contract — .gitignore covers tooling directories regenerated per run.
 *
 * Hallazgo_id: KHAL-A10 (auditoria-khal-2026-10-02.md §2-A10)
 * EVIDENCIA: `git status --short` reports `.vercel/`, `.worktrees/`,
 * `supabase/.temp/`, `scripts/` as untracked on every cycle.
 *
 * Tiger's contract: these paths MUST be ignored so nightly hydration stays
 * clean and a stray script never reaches main by accident.
 *
 * `scripts/create_orn59_ticket.py` was moved to trash (one-shot agent tool,
 * target ticket already exists); the whole `scripts/` dir is ignored and
 * empty in main.
 */

const ROOT = resolve(__dirname, '..', '..', '..');

const REQUIRED_IGNORE_ENTRIES: ReadonlyArray<{ path: string; reason: string }> = [
  { path: '.vercel/', reason: 'Vercel CLI project link (regenerated by `vercel link`)' },
  { path: '.worktrees/', reason: 'Hermes agent worktrees (per-task checkouts, never project source)' },
  { path: 'supabase/.temp/', reason: 'Supabase CLI local link state (regenerated by `supabase link/start`)' },
  { path: 'scripts/', reason: 'repo-local agent one-shot scripts (no source ownership; moved to trash)' },
];

const FORBIDDEN_COMMITS: ReadonlyArray<{ path: string; reason: string }> = [
  { path: 'scripts/create_orn59_ticket.py', reason: 'one-shot agent helper — ticket already created' },
];

describe('KHAL-A10 — .gitignore covers tooling directories', () => {
  const gitignorePath = resolve(ROOT, '.gitignore');
  const gitignore = readFileSync(gitignorePath, 'utf-8');
  const lines = gitignore.split(/\r?\n/).map((l) => l.trim());

  it.each(REQUIRED_IGNORE_ENTRIES)(
    'ignores $path — $reason',
    ({ path }) => {
      // Accept exact path with or without trailing slash, with or without leading slash
      const variants = [path, `/${path}`, path.replace(/\/$/, '')];
      const found = lines.some((l) => variants.includes(l));
      expect(found, `.gitignore must contain one of: ${variants.join(', ')}`).toBe(true);
    },
  );

  it('keeps prior protective entries (.env, .rdd/)', () => {
    expect(lines).toContain('.env');
    expect(lines).toContain('.rdd/');
  });
});

describe('KHAL-A10 — one-shot agent helpers are not tracked', () => {
  it.each(FORBIDDEN_COMMITS)(
    'scripts/$path is not in source control',
    ({ path }) => {
      const abs = resolve(ROOT, path);
      expect(existsSync(abs), `${path} must not exist in main (moved to trash)`).toBe(false);
    },
  );
});
